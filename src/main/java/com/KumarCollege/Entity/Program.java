package com.KumarCollege.Entity;

import com.KumarCollege.Enum.ProgramStatus;
import jakarta.persistence.*;
import lombok.Data;

import java.time.LocalDateTime;

@Entity
@Data
@Table(name = "programs")
public class Program {

    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    @Column(name = "program_id")
    private Long programId; // CHANGED: courseId -> programId

    @Column(name = "department_id", nullable = false)
    private Long departmentId;

    // CHANGED: Added because programs now reference degrees.
    @Column(name = "degree_id", nullable = false)
    private Long degreeId;

    @Column(name = "program_code", nullable = false, length = 30)
    private String programCode; // CHANGED: courseCode -> programCode

    @Column(name = "program_name", nullable = false, length = 150)
    private String programName; // CHANGED: courseName -> programName

    @Enumerated(EnumType.STRING)
    @Column(name = "status", nullable = false)
    private ProgramStatus status = ProgramStatus.ACTIVE;

    @Column(name = "created_at", insertable = false, updatable = false)
    private LocalDateTime createdAt; // CHANGED: generated by MySQL

    @Column(name = "updated_at", insertable = false, updatable = false)
    private LocalDateTime updatedAt; // CHANGED: generated by MySQL
}